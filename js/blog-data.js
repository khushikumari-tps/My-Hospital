window.ADV_BLOG = {
    posts: function () {
        return window.ADV_POSTS.slice().sort(function (a, b) {
            return a.date < b.date ? 1 : a.date > b.date ? -1 : 0;
        });
    },
    label: function (id) {
        var c = window.ADV_SECTIONS.filter(function (x) { return x.id === id; })[0];
        return c ? c.label : id;
    },
    bySlug: function (slug) {
        return window.ADV_POSTS.filter(function (p) { return p.slug === slug; })[0] || null;
    },
    /* related = same category first, then shared tags, newest first */
    related: function (slug, limit) {
        var self = this.bySlug(slug);
        if (!self) return this.posts().slice(0, limit || 3);
        return this.posts()
            .filter(function (p) { return p.slug !== slug; })
            .map(function (p) {
                var shared = p.cats.filter(function (c) { return self.cats.indexOf(c) > -1; }).length;
                return { p: p, score: shared + (p.section === self.section ? 3 : 0) };
            })
            .sort(function (a, b) { return b.score - a.score; })
            .slice(0, limit || 3)
            .map(function (x) { return x.p; });
    }
};
